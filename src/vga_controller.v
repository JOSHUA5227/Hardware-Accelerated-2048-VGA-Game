  localparam [255:0] TILE_16 = {
        16'b0000000000000000,
        16'b0000000000000000,
        16'b0001100111111000,
        16'b0111100111111000,
        16'b0111100110000000,
        16'b0001100110000000,
        16'b0001100110000000,
        16'b0001100111111100,
        16'b0001100111111100,
        16'b0001100110001100,
        16'b0001100110001100,
        16'b0001100110001100,
        16'b0001100111111100,
        16'b0001100111111100,
        16'b0000000000000000,
        16'b0000000000000000
  };

  localparam [255:0] TILE_32 = {
        16'b0000000000000000,
        16'b0000000000000000,
        16'b0111111001111110,
        16'b0111111001111110,
        16'b0000011000000110,
        16'b0000011000000110,
        16'b0000011000000110,
        16'b0111111001111110,
        16'b0111111001111110,
        16'b0000011001100000,
        16'b0000011001100000,
        16'b0000011001100000,
        16'b0111111001111110,
        16'b0111111001111110,
        16'b0000000000000000,
        16'b0000000000000000
  };

  localparam [255:0] TILE_64 = {
        16'b0000000000000000,
        16'b0000000000000000,
        16'b1111110001100011,
        16'b1111110001100011,
        16'b1100000001100011,
        16'b1100000001100011,
        16'b1100000001100011,
        16'b1111111001111111,
        16'b1111111001111111,
        16'b1100011000000011,
        16'b1100011000000011,
        16'b1100011000000011,
        16'b1111111000000011,
        16'b1111111000000011,
        16'b0000000000000000,
        16'b0000000000000000
  };

  localparam [255:0] TILE_128 = {
        16'b0000000000000000,
        16'b0000000000000000,
        16'b0000101110111000, 
        16'b0001101110111000,
        16'b0001100010101000,
        16'b0000100010101000,
        16'b0000100010101000,
        16'b0000101110111000,
        16'b0000101110111000,
        16'b0000101000101000,
        16'b0000101000101000,
        16'b0000101000101000,
        16'b0000101110111000,
        16'b0000101110111000,
        16'b0000000000000000,
        16'b0000000000000000
  };

  localparam [255:0] TILE_256 = {
        16'b0000000000000000,
        16'b0000000000000000,
        16'b0001110111011100,
        16'b0001110111011100,
        16'b0000010100010000,
        16'b0000010100010000,
        16'b0000010100010000,
        16'b0001110111011100,
        16'b0001110111011100,
        16'b0001000001010100,
        16'b0001000001010100,
        16'b0001000001010100,
        16'b0001110111011100,
        16'b0001110111011100,
        16'b0000000000000000,
        16'b0000000000000000
  };

  localparam [255:0] TILE_512 = {
        16'b0000000000000000,
        16'b0000000000000000,
        16'b0001110010111000,
        16'b0001110110111000,
        16'b0001000110001000,
        16'b0001000010001000,
        16'b0001000010001000,
        16'b0001110010111000,
        16'b0001110010111000,
        16'b0000010010100000,
        16'b0000010010100000,
        16'b0000010010100000,
        16'b0001110010111000,
        16'b0001110010111000,
        16'b0000000000000000,
        16'b0000000000000000
  };

  localparam [255:0] TILE_1024 = {
        16'b0000000000000000,
        16'b0000000000000000,
        16'b0010111011101010,
        16'b0110111011101010,
        16'b0110101000101010,
        16'b0010101000101010,
        16'b0010101000101010,
        16'b0010101011101110,
        16'b0010101011101110,
        16'b0010101010000010,
        16'b0010101010000010,
        16'b0010101010000010,
        16'b0010111011100010,
        16'b0010111011100010,
        16'b0000000000000000,
        16'b0000000000000000
  };

  localparam [255:0] TILE_2048 = {
        16'b0000000000000000,
        16'b0000000000000000,
        16'b0111011101010111,
        16'b0111011101010111,
        16'b0001010101010101,
        16'b0001010101010101,
        16'b0001010101010101,
        16'b0111010101110111,
        16'b0111010101110111,
        16'b0100010100010101,
        16'b0100010100010101,
        16'b0100010100010101,
        16'b0111011100010111,
        16'b0111011100010111,
        16'b0000000000000000,
        16'b0000000000000000
  };

    // Parameterized sizes
  localparam BOARD_SIZE = 320;  // variable board size; preferable range 256 - 400
  localparam BOARD_X = (640 - BOARD_SIZE) / 2;
  localparam BOARD_Y = (480 - BOARD_SIZE) / 2;
  localparam CELL_SIZE = BOARD_SIZE / 4;

  wire inside_board = (pix_x >= BOARD_X && pix_x < BOARD_X + BOARD_SIZE) &&
                      (pix_y >= BOARD_Y && pix_y < BOARD_Y + BOARD_SIZE);

  wire [9:0] rel_x = pix_x - BOARD_X;
  wire [9:0] rel_y = pix_y - BOARD_Y;
  wire [9:0] cell_x;
  wire [9:0] cell_y;

  assign {cell_x, col} = 	rel_x >= (CELL_SIZE * 3) ? {rel_x - 10'd240, 2'b11} : 
  							rel_x >= (CELL_SIZE * 2) ? {rel_x - 10'd160, 2'b10} :
							rel_x >= CELL_SIZE ? {rel_x - 10'd80, 2'b01} : {rel_x, 2'b00};

  assign {cell_y, row} = 	rel_y >= (CELL_SIZE * 3) ? {rel_y - 10'd240, 2'b11} : 
  							rel_y >= (CELL_SIZE * 2) ? {rel_y - 10'd160, 2'b10} :
							rel_y >= CELL_SIZE ? {rel_y - 10'd80, 2'b01} : {rel_y, 2'b00};

  wire center = (cell_x == CELL_SIZE/2 || cell_x == CELL_SIZE/2 - 1) 
  && (cell_y == CELL_SIZE/2 || cell_y == CELL_SIZE/2 - 1);

  wire is_large = (value >= 4'd7);

  wire [9:0] offset_small = (CELL_SIZE - 10'd32) >> 1;
  wire [9:0] offset_large = (CELL_SIZE - 10'd64) >> 1;

  wire [9:0] oy = offset_small;
  wire [9:0] ox = is_large ? offset_large : offset_small;
  wire [9:0] num_width = is_large ? 10'd64 : 10'd32;

  wire inside_text_box = (cell_x >= ox && cell_x < ox + num_width) && (cell_y >= oy && cell_y < oy + 9'd32);

  wire [9:0] gy = (cell_y - oy) >> 1;
  wire [9:0] gx = is_large ? (cell_x - ox) >> 2 : (cell_x - ox) >> 1;
  wire [7:0] bit_index = ~{gy[3:0], gx[3:0]};

  wire unused = &{gx[9:4],gx[1:0],gy[9:4],gy[1:0],1'b0};

  reg glyph_pixel;
  always @(*) begin
    case (value)
      4'h1: glyph_pixel = TILE_2[bit_index];
      4'h2: glyph_pixel = TILE_4[bit_index];
      4'h3: glyph_pixel = TILE_8[bit_index];
      4'h4: glyph_pixel = TILE_16[bit_index];
      4'h5: glyph_pixel = TILE_32[bit_index];
      4'h6: glyph_pixel = TILE_64[bit_index];
      4'h7: glyph_pixel = TILE_128[bit_index];
      4'h8: glyph_pixel = TILE_256[bit_index];
      4'h9: glyph_pixel = TILE_512[bit_index];
      4'hA: glyph_pixel = TILE_1024[bit_index];
      4'hB: glyph_pixel = TILE_2048[bit_index];
      default: glyph_pixel = 1'b0;
    endcase
  end

	reg [5:0] bg_colour;
	always @(*) begin
      case (value)
        4'h0: bg_colour = center ? 6'b11_11_11 : 6'b01_01_01; // Empty
        4'h1: bg_colour = 6'b11_01_01; // 2
        4'h2: bg_colour = 6'b11_10_01; // 4
        4'h3: bg_colour = 6'b11_11_00; // 8
        4'h4: bg_colour = 6'b00_11_11; // 16
        4'h5: bg_colour = 6'b00_10_11; // 32
        4'h6: bg_colour = 6'b00_11_10; // 64
        4'h7: bg_colour = 6'b00_11_01; // 128
        4'h8: bg_colour = 6'b11_01_00; // 256
        4'h9: bg_colour = 6'b11_01_10; // 512
        4'hA: bg_colour = 6'b10_01_11; // 1024
        4'hB: bg_colour = 6'b11_00_01; // 2048
        default: bg_colour = center ? 6'b11_11_11 : 6'b01_01_01;
      endcase
	end

	wire [5:0] tile_colour = (inside_text_box && glyph_pixel) ? 6'b00_00_00 : bg_colour;

	reg [5:0] rgb;
	always @(*) begin
		if(video_active) begin
			if(inside_board) rgb = tile_colour;
			else rgb = won ? 6'b00_10_01 : (lost ? 6'b11_00_00 : 6'b00_00_00);
		end else begin
			rgb = 6'b00_00_00;
		end
	end
 
	assign {R, G, B} = rgb;

endmodule
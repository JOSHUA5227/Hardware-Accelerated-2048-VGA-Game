        16'b0000111111110000,
        16'b0000000000000000,
        16'b0000000000000000
  };

  localparam [255:0] TILE_16 = {
        16'b0000000000000000,
        16'b0000000000000000,
        16'b0001100111111000,
        16'b0111100111111000,
        16'b0111100110000000,
        16'b0001100110000000,
        16'b0001100110000000,
        16'b0001100111111100,
        16'b0001100111111100,
        16'b0001100110001100,
        16'b0001100110001100,
        16'b0001100110001100,
        16'b0001100111111100,
        16'b0001100111111100,
        16'b0000000000000000,
        16'b0000000000000000
  };

  localparam [255:0] TILE_32 = {
        16'b0000000000000000,
        16'b0000000000000000,
        16'b0111111001111110,
        16'b0111111001111110,
        16'b0000011000000110,
        16'b0000011000000110,
        16'b0000011000000110,
        16'b0111111001111110,
